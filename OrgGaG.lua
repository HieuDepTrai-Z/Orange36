        prompt.MaxActivationDistance = math.huge
        prompt.Enabled = true
        prompt:InputHoldBegin()
        task.wait(0.05)
        prompt:InputHoldEnd()
        prompt.MaxActivationDistance = oldDist
        return true
    end
    return false
end

